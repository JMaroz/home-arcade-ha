/**
 * Normalizes input name or driver to search the catalog.
 */
function cleanDriverKey(input: string): string {
  return input
    .trim()
    .toLowerCase()
    .replace(/\.[a-zA-Z0-9]+$/, "") // remove file extension (.zip, .7z)
    .replace(/[^a-z0-9]/g, "");    // strip symbols
}

/**
 * Resolves an arcade / Neo Geo ROM file name or driver stem to its canonical metadata.
 */
export function getArcadeGameInfo(system: string, nameOrDriver: string): ArcadeGameInfo | null {
  if (!nameOrDriver) return null;

  const key = cleanDriverKey(nameOrDriver);
  const sysLower = (system || "").toLowerCase();

  // 1. Direct driver lookup
  if (sysLower === "neogeo") {
    if (NEOGEO_GAMES[key]) return NEOGEO_GAMES[key];
    if (ARCADE_GAMES[key]) return ARCADE_GAMES[key];
  } else if (sysLower === "arcade" || sysLower === "mame") {
    if (ARCADE_GAMES[key]) return ARCADE_GAMES[key];
    if (NEOGEO_GAMES[key]) return NEOGEO_GAMES[key];
  } else {
    if (NEOGEO_GAMES[key]) return NEOGEO_GAMES[key];
    if (ARCADE_GAMES[key]) return ARCADE_GAMES[key];
  }

  // 2. Check title / canonicalName match (e.g. if title is already "Metal Slug")
  const normInput = nameOrDriver.toLowerCase().replace(/[^a-z0-9]/g, "");
  const searchPool = sysLower === "neogeo"
    ? [...Object.values(NEOGEO_GAMES), ...Object.values(ARCADE_GAMES)]
    : [...Object.values(ARCADE_GAMES), ...Object.values(NEOGEO_GAMES)];

  for (const game of searchPool) {
    const cleanT = game.title.toLowerCase().replace(/[^a-z0-9]/g, "");
    const cleanC = game.canonicalName.toLowerCase().replace(/[^a-z0-9]/g, "");
    if (cleanT === normInput || cleanC === normInput || normInput.startsWith(cleanT)) {
      return game;
    }
  }

  return null;
}

/**
 * Returns true if a string looks like a short arcade driver name (e.g. "mslug", "kof98", "sf2").
 */
export function isArcadeDriverName(name: string): boolean {
  const key = cleanDriverKey(name);
  return Boolean(NEOGEO_GAMES[key] || ARCADE_GAMES[key]);
}
